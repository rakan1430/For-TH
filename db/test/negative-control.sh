#!/usr/bin/env bash
# =============================================================================
# إثبات أنّ الفحص ليس أعمى — البند ٢٢
#
# «فحصٌ لا يلتقط شيئاً لا قيمة له حتى تُثبت أنّه يستطيع.»
#
# ووقع مراراً أن فحصاً «نجح» لأنّه كان يقيس الشيء الخطأ. فلا يكفي أن ترى
# مجموعة الفحوص خضراء: عليك أن تُعيد إدخال الخلل الذي بُنيت لالتقاطه عمداً،
# وتتأكّد أنّها **تصرخ**.
#
# فهنا نُعيد إدخال خمسة أخطاء وقع مثلها فعلاً، واحداً واحداً، ونشترط على
# مجموعة الفحوص أن ترسب في كل مرّة. ولو نجحت مرّةً واحدة فالخضرة كذبٌ،
# وهذا السكربت هو الذي يكشفه.
# =============================================================================
set -Eeuo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

green() { printf '\033[32m%s\033[0m\n' "$*"; }
red()   { printf '\033[31m%s\033[0m\n' "$*"; }
bold()  { printf '\n\033[1m%s\033[0m\n' "$*"; }

LOG="$(mktemp)"
trap 'rm -f "$LOG"' EXIT
FAILURES=0

bold "أوّلاً: المجموعة نظيفةً يجب أن تنجح"
if ./db/test/run.sh > "$LOG" 2>&1; then
  green "  ✓ نجحت على قاعدةٍ سليمة"
else
  red "  ✗ رسبت وهي سليمة — أصلح ذلك قبل أي شيء"
  tail -40 "$LOG" >&2
  exit 1
fi

bold "ثانياً: مع كل خللٍ مقصود يجب أن ترسب"
for flaw in db/test/flaws/*.sql; do
  name="$(basename "$flaw")"
  desc="$(sed -n '2s/^-- //p' "$flaw")"
  printf '\n  ── %s\n     %s\n' "$name" "$desc"

  if INJECT_SQL="$flaw" ./db/test/run.sh > "$LOG" 2>&1; then
    red   "     ✗ مرّت المجموعة رغم الخلل — الفحص أعمى عن هذه الحالة"
    FAILURES=$((FAILURES + 1))
  else
    # ونطبع ما الذي صرخ بالضبط، فلا يكفي أن ترسب: يجب أن ترسب **للسبب الصحيح**.
    caught="$(grep -m1 -E 'فشل التحقّق|تخالف القائمة البيضاء' "$LOG" | sed 's/^[^:]*: *//' || true)"
    green "     ✓ رسبت كما يجب"
    [[ -n "$caught" ]] && printf '        التقطها: %s\n' "$caught"
  fi
done

bold "النتيجة"
if [[ $FAILURES -eq 0 ]]; then
  green "كل خللٍ مقصود التقطته المجموعة. الفحوص تميّز، ونجاحها يعني شيئاً."
else
  red "$FAILURES خللاً مرّ دون أن يُلتقط. المجموعة تحتاج فحصاً لكلٍّ منها."
  exit 1
fi
