-- =============================================================================
-- ٠٠١٣ — المالك الحقيقيّ، والأسعار
--
-- ثلاثة قراراتٍ وصلت من صاحب المنصّة (أ. محمد الشرطي):
--   ١) حسابه معلّمٌ كامل، ويبقى المبرمج معلّماً ما دام يبني.
--   ٢) اشتراكٌ واحد: ثلاثة أشهر بـ١٥٠ ريالاً. لا شهريّ.
--   ٣) اسم المنصّة «إتقان الشرطي» — في الواجهة لا في القاعدة.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- ١) معلّمون بالانتظار
--
-- ⚠️ المشكلة: `private.teachers.user_id` مفتاحٌ أجنبيّ إلى `auth.users`. وصاحب
--    المنصّة لم يدخل بعد، فلا صفّ له هناك — ولا يمكن ترقيته قبل أن يدخل.
--    والبديل الساذج «ننتظر حتى يدخل ثمّ يُشغَّل SQL» يجعل أوّل دخولٍ له
--    شاشةَ طالبٍ بلا اشتراك، ويحتاج تدخّلاً يدوياً في لحظةٍ لا يكون فيها
--    أحدٌ حاضراً.
--
-- ⚠️ فالترقية **معلَنةٌ مسبقاً بالبريد**، وتقع لحظة إنشاء المستخدم. والبريد
--    هنا ليس ادّعاءً من المتصفّح: يكتبه خادمُ المصادقة بعد أن يُثبته Google.
--
-- ⚠️ والجدول في `private`: لا مسار شبكة يبلغه، ولا سياسة تفتحه. من يُضاف
--    هنا يُضاف بـSQL مباشرةً — كما يُضاف المعلّم تماماً. ولو كان في `public`
--    لصار بابَ ترقيةٍ ذاتية: يكتب الطالب بريده فيه فيصير معلّماً.
-- -----------------------------------------------------------------------------
create table if not exists private.pending_teachers (
  email      text primary key check (position('@' in email) > 1),
  note       text,
  added_at   timestamptz not null default now()
);

revoke all on table private.pending_teachers from public, anon, authenticated;

-- -----------------------------------------------------------------------------
-- ٢) الترقية لحظة إنشاء المستخدم
--
-- ⚠️ `security definer` لازمة: المحفّز يعمل في سياق خادم المصادقة، ولا
--    صلاحية له على `private`.
--
-- ⚠️ والمقارنة على البريد بحروفٍ صغيرة: Google يعيده كما سجّله صاحبه، وقد
--    يختلف الرسم بين تسجيلين. وبريدٌ يخطئ حرفاً واحداً في حالته لا يُرقّى،
--    فيبقى صاحب المنصّة طالباً ولا أحد يعرف لماذا.
--
-- ⚠️ ولا يُحذف صفّ الانتظار بعد الترقية: لو حُذف الحساب يوماً وأُعيد إنشاؤه
--    لَعاد معلّماً بلا تدخّل. وبقاؤه لا يضرّ — `on conflict do nothing`.
-- -----------------------------------------------------------------------------
create or replace function private.promote_pending_teacher()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (
    select 1 from private.pending_teachers p
    where lower(p.email) = lower(coalesce(new.email, ''))
  ) then
    insert into private.teachers (user_id, note)
    values (new.id, 'رُقّي تلقائياً من قائمة الانتظار')
    on conflict (user_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists promote_pending_teacher on auth.users;
create trigger promote_pending_teacher
  after insert on auth.users
  for each row execute function private.promote_pending_teacher();

-- -----------------------------------------------------------------------------
-- ٣) الأسعار: ثلاثة أشهر بـ١٥٠ ريالاً، ولا شهريّ
--
-- ⚠️ الخطط الشهرية **تُعطَّل ولا تُحذف**: `subscriptions` لا يشير إليها،
--    لكنّ `subscription_requests.plan_id` يشير. وحذف خطّةٍ يحمل طلباً قديماً
--    يمحو سجلّ ما طلبه الطالب فعلاً — أو يُسقط الحذف بخطأ مفتاحٍ أجنبيّ.
--    والتعطيل يُخفيها عن الطالب ويُبقي التاريخ.
--
-- ⚠️ والسعر بالوحدة الصغرى (هللات): ١٥٠ ريالاً = ١٥٠٠٠. وتخزين الأموال
--    كأعدادٍ صحيحة لا عشرية قاعدةٌ لا تُنقَض — العشريّ يجمع خطأً كسرياً.
-- -----------------------------------------------------------------------------
update public.plans
   set price_minor = 15000, currency = 'SAR', is_active = true
 where period = 'quarterly';

update public.plans
   set is_active = false
 where period = 'monthly';

-- -----------------------------------------------------------------------------
-- ٤) الصلاحيات — التقط فحصُ القائمة البيضاء هذه الدالّة فور إضافتها
--
-- ⚠️ دالّة المحفّز **لا تحتاج `EXECUTE` لأحد**: التحقّق من الصلاحية يقع عند
--    `create trigger` لا عند إطلاقه، فالمحفّز يعمل بعد السحب. وتركها
--    ممنوحةً لـPUBLIC يعني دالّةً `security definer` تكتب في `private`
--    يستطيع أيّ دورٍ استدعاءها مباشرةً — وهي تقبل صفّاً يختار المستدعي
--    بريده. أي بابُ ترقيةٍ ذاتية بعينه.
-- -----------------------------------------------------------------------------
revoke all on function private.promote_pending_teacher() from public, anon, authenticated;
